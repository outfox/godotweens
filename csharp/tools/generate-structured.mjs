// Generate immutable definitions from the existing property adapters.
// Run: node csharp/tools/generate-structured.mjs [--check | --patch]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const qualify = type => /^(float|double|int|bool|TValue|TTarget)$/.test(type) || type.startsWith('Godot.') ? type : 'Godot.' + type;
const optionsSource = fs.readFileSync(path.join(root, 'src/Core/TweenOptions.cs'), 'utf8');
const options = [...optionsSource.split('public class TweenOptionsBuilder')[1].matchAll(/public ([\w.<>?, ]+) (\w+) \{ get; set; \}/g)].map(m => [m[1], m[2]]);
const header = '// SPDX-License-Identifier: MIT\n// SPDX-FileCopyrightText: 2026 Moritz Voss\n\n// <auto-generated by csharp/tools/generate-structured.mjs />\n#nullable enable\nusing tweens.gd;\n\nnamespace Tweens;\n\n';

function definition(name, target, value, generic = '', parameter = false, custom = false) {
    target = qualify(target);
    value = qualify(value);
    const short = name.replace(/Tween$/, '');
    const type = short + generic;
    const instance = 'TweenInstance<' + target + ', ' + value + '>';
    const binding = 'TweenDefinition<' + target + ', ' + value + '>';
    const contract = 'ITweenDefinition<' + target + ', ' + value + '>';
    const callbacks = ['OnAdd', 'OnStart', 'OnUpdate', 'OnEnd', 'OnCancel', 'OnFinally'];
    const members = ['From', 'To', ...callbacks];
    const constraints = custom ? '\n    where TTarget : class where TValue : struct' : generic ? '\n    where TValue : struct' : '';
    let result = '/// <summary>Reusable immutable ' + short + ' configuration. Each start creates independent playback.</summary>\npublic readonly record struct ' + type + ' : ' + contract + constraints + '\n{\n';
    result += '    public TweenOptions Options { get; init; }\n';
    result += options.map(([t, n]) => '    public ' + t + ' ' + n + ' { get => Options.' + n + '; init => Options = Options with { ' + n + ' = value }; }').join('\n') + '\n\n';
    result += '    public ' + value + '? From { get; init; }\n    public ' + value + '? To { get; init; }\n';
    result += callbacks.map(n => '    public Action<' + instance + (n === 'OnUpdate' ? ', ' + value : '') + '>? ' + n + ' { get; init; }').join('\n') + '\n';
    if (parameter) result += '\n    public string Parameter { get; init; }\n    public ' + short + '(string parameter) => Parameter = parameter;\n';
    if (custom) result += '\n    public Func<TTarget, TValue> Getter { get; init; }\n    public Action<TTarget, TValue> Setter { get; init; }\n    public Func<TValue, TValue, float, TValue> Interpolate { get; init; }\n\n    public Property(Func<TTarget, TValue> getter, Action<TTarget, TValue> setter, Func<TValue, TValue, float, TValue> interpolate)\n    {\n        Getter = getter;\n        Setter = setter;\n        Interpolate = interpolate;\n    }\n';
    result += '\n    ' + binding + ' ' + contract + '.CreatePlayback()\n    {\n        var playback = new tweens.gd.' + name + generic + (parameter ? '(Parameter)' : custom ? '(Getter, Setter, Interpolate)' : '') + '\n        {\n';
    result += members.map(n => '            ' + n + ' = ' + n + ',').join('\n') + '\n        };\n        Options.CopyTo(playback);\n        return playback;\n    }\n}\n';
    return result;
}

const generated = new Map();
for (const file of fs.readdirSync(path.join(root, 'src/Tweens')).sort()) {
    const source = fs.readFileSync(path.join(root, 'src/Tweens', file), 'utf8');
    const matches = [...source.matchAll(/public sealed class (\w+)\(\) : PropertyTween<([^,]+), ([^>]+)>/g)];
    if (matches.length) generated.set(file.replace('.cs', '.g.cs'), header + matches.map(([, name, target, value]) => definition(name, target, value)).join('\n'));
}
generated.set('ShaderParameters.g.cs', header + [
    ['ShaderParameterTween', 'ShaderMaterial'],
    ['CanvasItemInstanceShaderParameterTween', 'CanvasItem'],
    ['GeometryInstanceShaderParameterTween', 'GeometryInstance3D'],
].map(([name, target]) => definition(name, target, 'TValue', '<TValue>', true)).join('\n'));
generated.set('Property.g.cs', header + definition('PropertyTween', 'TTarget', 'TValue', '<TTarget, TValue>', false, true));

const output = path.join(root, 'src/Structured');
let patch = '*** Begin Patch\n';
let stale = false;
for (const [file, content] of generated) {
    const dest = path.join(output, file);
    const current = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8').replaceAll('\r\n', '\n') : null;
    if (content === current) continue;
    stale = true;
    if (process.argv.includes('--patch')) {
        const relative = path.relative(process.cwd(), dest).replaceAll('\\', '/');
        patch += current === null ? '*** Add File: ' + relative + '\n' : '*** Update File: ' + relative + '\n@@\n' + current.trimEnd().split('\n').map(l => '-' + l).join('\n') + '\n';
        patch += content.trimEnd().split('\n').map(l => '+' + l).join('\n') + '\n';
    } else if (!process.argv.includes('--check')) {
        fs.mkdirSync(output, { recursive: true });
        fs.writeFileSync(dest, content);
    }
}
if (process.argv.includes('--patch')) console.log(patch + '*** End Patch');
if (process.argv.includes('--check') && stale) {
    console.error('Structured definitions are stale. Run node csharp/tools/generate-structured.mjs');
    process.exitCode = 1;
}
